"""Real camera calibration -> sim/cameras.yaml (calibrated poses + intrinsics at the streamed resolution).

    python sim/calibration_to_cameras.py                         # print what would be written
    python sim/calibration_to_cameras.py --write                 # rewrite sim/cameras.yaml
    python sim/calibration_to_cameras.py --calib-dir /path/to/camera_calibration --robot right_fr3 --stream 640 480

Input: the hand-eye calibration repo (camera/camera_calibration): results/calibration.yaml (poses, metres) and
config/<camera>.yaml (intrinsics at the capture resolution, 1280x720).
  front = the "ego" D435i:  T_base_ego is in the calibrated arm's base frame (fr3_link0); the arm's mount in the sim
                            world (rail_link, rail at 0) comes from the URDF, so  T_world_front = T_world_base @ T_base_ego.
  wrist = the D405s:        T_ee_hand is relative to the FLANGE (fr3_link8). One arm is calibrated; the other wrist uses
                            the same transform (same rigid mount; also what crisp_camera_bringup does).
Intrinsics: RealSense 4:3 modes (e.g. 640x480) are the 16:9 image scaled to the height and centre-cropped in width, so
fx, fy and cy scale by H / 720 and cx also shifts by the crop. The sim renders square pixels about the image centre:
hfov comes from fx; the principal-point offset (a few pixels) is recorded, not rendered.
Poses are written as 4x4 matrices in the OpenCV optical convention (x right, y down, z forward); sim/duo_env.py converts.
The board pose is reported too: it lies on the real table, which gives the real table height in the sim world.
"""
import argparse
import os
import sys
from datetime import datetime

import numpy as np
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from duo_kin import Chain  # noqa: E402

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("--calib-dir", default=os.path.join(HERE, "..", "camera", "camera_calibration"))
ap.add_argument("--robot", default="right_fr3", help="calibrated arm whose session to use (calibration.yaml robots.<name>)")
ap.add_argument("--front", default="ego", help="calibrated static camera that becomes the sim 'front' camera")
ap.add_argument("--stream", type=int, nargs=2, default=[640, 480], metavar=("W", "H"),
                help="resolution the real cameras stream at (crisp_camera_bringup streams.profile)")
ap.add_argument("--variant", default="actual", choices=["actual", "upright"])
ap.add_argument("--out", default=os.path.join(HERE, "cameras.yaml"))
ap.add_argument("--write", action="store_true")
a = ap.parse_args()

cal_all = yaml.safe_load(open(os.path.join(a.calib_dir, "results", "calibration.yaml")))
cal = cal_all["robots"][a.robot]
if not cal.get("passed", False):
    raise SystemExit(f"calibration for {a.robot} did not pass its checks: {cal.get('warnings')}")
cams = cal["cameras"]
hand = next(n for n, c in cams.items() if c.get("mount") == "eye_in_hand")
side = a.robot.split("_")[0]                                       # right_fr3 -> right
q0 = np.zeros(7)
T_world_base = Chain(f"{side}_fr3_link0", arm_prefix=f"{side}_fr3_joint", variant=a.variant).fk(q0)
T_base_front = np.array(cams[a.front][f"T_base_{a.front}"], float)
T_flange_wrist = np.array(cams[hand][f"T_ee_{hand}"], float)
T_world_front = T_world_base @ T_base_front
T_world_board = T_world_base @ np.array(cal["T_base_board"], float)


def intrinsics(name):
    c = yaml.safe_load(open(os.path.join(a.calib_dir, "config", f"{name}.yaml")))
    K, W0, H0 = np.array(c["K"], float), c["width"], c["height"]
    W, H = a.stream
    s = H / H0
    if W > W0 * s + 1e-6:
        raise SystemExit(f"{name}: stream {W}x{H} is wider than the scaled {W0}x{H0} image; only height-scaled crops are handled")
    fx, fy, cx, cy = K[0, 0] * s, K[1, 1] * s, K[0, 2] * s - (W0 * s - W) / 2, K[1, 2] * s
    return dict(resolution=[W, H], hfov_deg=round(float(np.degrees(2 * np.arctan(W / 2 / fx))), 3),
                fx=round(fx, 2), fy=round(fy, 2), cx=round(cx, 2), cy=round(cy, 2), serial=str(c.get("serial")))


fi, wi = intrinsics(a.front), intrinsics(hand)
old = yaml.safe_load(open(a.out)) if os.path.exists(a.out) else {}
clip_f = old.get("front", {}).get("clip", [0.05, 8.0])
clip_w = old.get("wrist", {}).get("clip", [0.02, 5.0])
sim = old.get("sim", {"fps": 15, "substeps": 8})
board_c = (T_world_board @ np.array([0.0875, 0.1225, 0.0, 1.0]))[:3]      # centre of the 5 x 7 x 35 mm board
fwd = T_world_front[:3, 2]
mat = lambda T: [[round(float(v), 6) for v in row] for row in T]
src = os.path.relpath(os.path.join(a.calib_dir, "results", "calibration.yaml"), os.path.join(HERE, ".."))

text = f"""# Camera rig for sim/duo_env.py. GENERATED by sim/calibration_to_cameras.py from the real hand-eye calibration
#   {src}  (robot {a.robot}, {cal.get('timestamp')}, session {os.path.basename(str(cal.get('session')))})
# on {datetime.now().strftime('%Y-%m-%d %H:%M')}. Re-run that script after re-calibrating instead of editing the poses here.
# Units: metres, world frame = rail_link frame (rail at 0), +z up. The effective values (and the same numbers after the
# square crop) are copied into every recorded dataset as cameras.json.
# Poses: 4x4, OpenCV optical frame (x right, y down, z forward). Intrinsics are those of the {a.stream[0]}x{a.stream[1]} stream
# (crisp_camera_bringup); the sim renders square pixels about the image centre (cx, cy recorded, not rendered).
front:                       # the real "{a.front}" D435i (serial {fi['serial']}), fixed
  # at {np.round(T_world_front[:3, 3], 3).tolist()}, looking {np.degrees(np.arcsin(-fwd[2])):.1f} deg below horizontal; vertical FOV {np.degrees(2 * np.arctan(a.stream[1] / 2 / fi['fy'])):.1f} deg
  T_world_cam: {mat(T_world_front)}
  resolution: {fi['resolution']}
  hfov_deg: {fi['hfov_deg']}
  fx: {fi['fx']}
  fy: {fi['fy']}
  cx: {fi['cx']}
  cy: {fi['cy']}
  clip: {clip_f}
wrist:                       # the D405s: calibrated "{hand}" (serial {wi['serial']}) flange -> camera; the other wrist uses the same mount
  T_flange_cam: {mat(T_flange_wrist)}
  resolution: {wi['resolution']}
  hfov_deg: {wi['hfov_deg']}
  fx: {wi['fx']}
  fy: {wi['fy']}
  cx: {wi['cx']}
  cy: {wi['cy']}
  clip: {clip_w}             # far clip bounds the depth the wrist cameras can see (beyond clip = no reading = 0)
scene:
  table_z: {board_c[2]:.3f}             # real table top in this frame: the calibration board lay flat on it (+- a few mm board thickness)
sim:
  fps: {sim['fps']}                    # policy rate; one action per step
  substeps: {sim['substeps']}                # physics steps (1/120 s) per policy step
# The calibration board lay on the real table with its centre at {np.round(board_c, 3).tolist()} in this frame.
"""
print(text)
if a.write:
    with open(a.out, "w") as fh:
        fh.write(text)
    print(f"wrote {a.out}")
